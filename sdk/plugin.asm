; Плагин подключает только этот файл:
;       include "plugin.asm"
;       PLUGIN_HEADER PLG_EXPORT,"PT3","Pro Tracker 3"
;   PluginMain:
;       ...
;       xor a           ; A = 0 - успех, иначе код ошибки ERR_*
;       ret
