; =========================================================================
; ПЕРЕКЛЮЧЕНИЕ СТРАНИЦ
; =========================================================================
; SETPAGEn page - сохранить текущую страницу окна n на стек и включить page
; RESTPAGEn     - вернуть со стека. Парные как push/pop. Портят A, BC.
; page - число, регистр или (hl). Переменную - только через регистр:
;       ld a,(SV_SONG_PAGE)
;       SETPAGE3 a              ; НЕ SETPAGE3 (SV_SONG_PAGE) - соберётся молча, но неверно

    MACRO SETPAGE win,page
        ld b,page
        ld a,(SV_PAGES+win)
        push af
        ld a,b
        ld (SV_PAGES+win),a
        ld bc,#10AF+win*#100
        out (c),a
    ENDM

    MACRO RESTPAGE win
        pop af
        ld (SV_PAGES+win),a
        ld bc,#10AF+win*#100
        out (c),a
    ENDM

    MACRO SETPAGE2 page
        SETPAGE 2,page
    ENDM
    MACRO SETPAGE3 page
        SETPAGE 3,page
    ENDM
    MACRO RESTPAGE2
        RESTPAGE 2
    ENDM
    MACRO RESTPAGE3
        RESTPAGE 3
    ENDM

