; =========================================================================
; ПАТТЕРНЫ - внутреннее для трекера
; =========================================================================
; Формат паттерна (CH_*, CHIP_*, PAT_TEXT ...) описан в sdk/plugin.asm,
; здесь только вспомогательное. Паттерн = целая страница.

; --- адрес ячейки --------------------------------------------------------
; PAT_ADDR base_h,row,chip,field -> HL, портит A
; base_h - старший байт окна со страницей паттерна (#80 для окна 2)
; row - номер роу (число или регистр), остальное - константы
; пример: PAT_ADDR #80,c,1,CHIP_CH_B+CH_VOLUME  -> громкость канала E, роу C
    MACRO PAT_ADDR base_h,row,chip,field
        ld a,row
        add a,base_h
        ld h,a
        ld l,chip*CHIP_SIZE+field
    ENDM
