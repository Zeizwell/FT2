; =========================================================================
; ПАТТЕРНЫ - внутреннее для трекера
; =========================================================================
; Формат паттерна (CH_*, CMD_*, CHIP_*, PAT_WIDTH ...) описан в sdk/plugin.asm,
; здесь только вспомогательное.

; --- адрес ячейки --------------------------------------------------------
; PAT_ADDR base_h,row,slot,chip,field -> HL, портит A
; base_h - старший байт окна со страницей паттернов (#80 для окна 2)
; row - номер строки (число или регистр), остальное - константы
; пример: PAT_ADDR #80,c,0,1,CHIP_CH_B+CH_VOLUME  -> громкость канала E, строка C
    MACRO PAT_ADDR base_h,row,slot,chip,field
        ld a,row
        add a,base_h
        ld h,a
        ld l,slot*PAT_WIDTH+chip*CHIP_SIZE+field
    ENDM
