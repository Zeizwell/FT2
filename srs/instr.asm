; =========================================================================
; ИНСТРУМЕНТЫ И ОРНАМЕНТЫ: страницы трека (формат - sdk/plugin.asm, как в FTC)
; =========================================================================
; Инструменты - страница Trk_Ins: 32 блока по INS_BLOCK с #0000. Орнаменты - страница Trk_Orn: 32 блока
; по ORN_BLOCK с #0000. Имена инструментов - в странице трека (SONG_INS_NAMES).
; Страница - в окне 2 на время вызова (SETPAGE2 / RESTPAGE2 внутри).
; =========================================================================

;-------- Пустые инструменты и орнаменты текущего трека (Trk_Ins, Trk_Orn): все инструменты - одна строка
; "тон, громкость 15", все орнаменты - одна нулевая строка
Ins_Clear
        ld a,(Trk_Ins)
        SETPAGE2 a
        call .zero                  ; всё в нули
        ld hl,#8000+OH_ROWS         ; инструменты: строка 0
        ld b,SAMPLES_MAX
        ld de,INS_BLOCK
.i      ld (hl),1<<IRB_OFF          ; шум выключен, тон 0 (включён)
        push hl
        inc hl
        inc hl
        inc hl
        ld (hl),15                  ; огибающая выключена, громкость 15
        pop hl
        add hl,de
        djnz .i
        RESTPAGE2
        ld a,(Trk_Orn)              ; орнаменты: нули = одна строка без сдвига
        SETPAGE2 a
        call .zero
        RESTPAGE2
        ret
; окно 2 - в нули
.zero   ld hl,#8000
        ld de,#8001
        ld bc,#3FFF
        ld (hl),0
        ldir
        ret

;-------- Блок в страницу. A - страница, HL - готовый блок (заголовок + строки +
; хвост), DE - смещение блока в странице (n*INS_BLOCK или n*ORN_BLOCK),
; BC - длина блока
; (BC, DE - через память: SETPAGE кладёт страницу на стек, push вокруг него нельзя)
Ip_BC           dw 0
Ip_DE           dw 0

Ins_Put
        ld (Ip_BC),bc
        ld (Ip_DE),de
        SETPAGE2 a
        ld de,(Ip_DE)
        ld bc,(Ip_BC)
        set 7,d                     ; страница - в окне 2 (#8000)
        ldir
        RESTPAGE2
        ret
