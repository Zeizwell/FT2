; =========================================================================
; ИНСТРУМЕНТЫ И ОРНАМЕНТЫ: страница трека (формат - sdk/plugin.asm, как в FTC)
; =========================================================================
; Страница целиком: 32 инструмента по INS_BLOCK с #0000, 16 орнаментов по
; ORN_BLOCK с ORN_BASE. Здесь - заготовка пустой страницы и запись блока.
; Страница - в окне 2 на время вызова (SETPAGE2 / RESTPAGE2 внутри).
; =========================================================================

;-------- Пустая страница: все инструменты - одна строка "тон, громкость 15",
; все орнаменты - одна нулевая строка. A - страница
Ins_Clear
        SETPAGE2 a
        ld hl,#8000                 ; всё в нули
        ld de,#8001
        ld bc,#3FFF
        ld (hl),0
        ldir
        ld hl,#8000+OH_ROWS         ; инструменты: строка 0
        ld b,SAMPLES_MAX
        ld de,INS_BLOCK
.i      ld (hl),1<<IRB_OFF          ; шум выключен, тон 0 (включён)
        push hl
        inc hl
        inc hl
        inc hl
        ld (hl),15                  ; огибающая выключена, громкость 15
        pop hl
        add hl,de
        djnz .i
        RESTPAGE2                   ; орнаменты: нули = одна строка без сдвига
        ret

;-------- Блок в страницу. A - страница, HL - готовый блок (заголовок + строки +
; хвост), DE - смещение блока в странице (n*INS_BLOCK или ORN_BASE+n*ORN_BLOCK),
; BC - длина блока
; (BC, DE - через память: SETPAGE кладёт страницу на стек, push вокруг него нельзя)
Ip_BC           dw 0
Ip_DE           dw 0

Ins_Put
        ld (Ip_BC),bc
        ld (Ip_DE),de
        SETPAGE2 a
        ld de,(Ip_DE)
        ld bc,(Ip_BC)
        set 7,d                     ; страница - в окне 2 (#8000)
        ldir
        RESTPAGE2
        ret
