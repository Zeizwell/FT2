; Раскладка одна на все темы (роли srs/colors.asm не зависят от темы):
;   #0 чёрный, #1-#3 тёмные оттенки темы (фоны, плашки), #4 тёмно-серый,
;   #5-#9 средние и светлые оттенки темы (текст, номера, кнопки),
;   #A янтарь, #B зелёный, #C голубой (курсор), #D красный, #E серый, #F белый - во всех одинаковые.
; Цвет: [gggBBBBB] [0RRRRRGG]. Только уровни ЦАП 0, 8, 16, 24: младшие биты - ШИМ, без VDAC
; дают полосы на экране. Палитра 13 (PALET_NUM, video.asm).
; =========================================================================
PALETTES        equ 6

Cur_Palette     db 0                ; выбранная тема
Pal_Bg          dw 0                ; её цвет #0 (фон) - для полосы времени
Cur_Blink       db 0                ; курсор паттерна: 0 - сплошной, 1 - мигающий (Setup, INI)
Auto_Path       ds 120              ; INI load=: трек при старте (путь от корня, 0 - нет). Setup Save пишет обратно
Auto_Go         db 0                ; 1 - загрузить при старте (делает Disk, сбрасывает)

;-------- Тема A: 16 цветов в CRAM (DMA). Портит AF, BC, DE, HL
Set_Palette
        call Pal_Prep
        ld hl,Pal_Dma               ; 16 цветов - в CRAM через DMA (запись ЦП через
        jp set_ports                ;   FM-окно портит память под ним)

;-------- То же при старте (Init_Video_90x36): прерывания выключены и включать их ещё
; нельзя - set_ports делает EI, поэтому без него
Set_Palette_Di
        call Pal_Prep
        ld hl,Pal_Dma
        jp set_ports_int

; Тема A -> Cur_Palette, Pal_Bg, источник Pal_Dma
Pal_Prep
        ld (Cur_Palette),a
        add a,a                     ; *32
        add a,a
        add a,a
        add a,a
        add a,a
        ld l,a
        ld h,0
        ld de,Pal_Data
        add hl,de
        ld e,(hl)                   ; фон - для полосы времени
        inc hl
        ld d,(hl)
        dec hl
        ld (Pal_Bg),de
        ld a,l                      ; источник DMA - эта тема (коре, страница 0)
        ld (Pal_Dma+1),a
        ld a,h
        ld (Pal_Dma+3),a
        ret

PAL_CRAM        equ PALET_NUM*16    ; первый цвет палитры 13 в CRAM
Pal_Dma db high DMASADDRL,0, high DMASADDRH,0, high DMASADDRX,PAGE_CORE0
        db high DMADADDRL,(PAL_CRAM&127)*2, high DMADADDRH,PAL_CRAM>>7, high DMADADDRX,0
        db high DMALEN,16-1, high DMANUM,0, high DMACTR,DMA_RAM_CRAM, #FF

