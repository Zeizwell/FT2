; =========================================================================
; МОДУЛЬ УПРАВЛЕНИЯ ВИДЕОРЕЖИМОМ TS-CONF (ОФИЦИАЛЬНЫЙ ТЕКСТ 90x36)
; =========================================================================

PALET_NUM   equ 13  ; Номер палитры для текстового режима

; Шрифт автоматически ищется ПЛИС в странице PAGE_TEXT XOR 1 (= PAGE_FONT)

Init_Video_90x36:
    ; 1. Включаем текстовый режим. 
    ; Разрешение ставим VID_360X288 (чтобы получить 90 символов в ширину)
    ; и подмешиваем флаг текстового режима VID_TEXT.
    ld bc, VCONFIG
    ld a, VID_360X288 | VID_TEXT
    out (c), a

    ; 2. ПОЛНОСТЬЮ ОТКЛЮЧАЕМ СЛОИ ТАЙЛОВ И СПРАЙТОВ
    ; Текстовому режиму они не нужны, их включение плодило кашу!
    ;ld bc, TSCONFIG
    ;ld a, TSU_T0EN                   ; Активируем Tiles 0 (#20
    ;out (c), a

    ; 3. Выбираем базовую палитру 
    ld bc, PALSEL
    ld a,PALET_NUM   
    out (c), a

    ; 4. УКАЗЫВАЕМ СТРАНИЦУ ТЕКСТОВОГО ЭКРАНА В ПОРТ VPAGE ($01AF)
    ld bc, VPAGE
    ld a, PAGE_TEXT
    out (c), a

    ld bc, T0GPAGE
    ld a, PAGE_TEXT     ; ПЛИС возьмет экран из PAGE_TEXT,
    out (c), a

    ; 5. ЗАЛИВАЕМ ЦВЕТА (Оставляем её, чтобы буквы не были чёрными!)
    call Load_Text_Palette
    ld bc, VPAGE
    ld a, PAGE_TEXT
    out (c), a
    ret

; -------------------------------------------------------------------------
; ЗАЛИВКА БАЗОВОЙ ПАЛИТРЫ ЧЕРЕЗ DMA (RAM -> CRAM)
; -------------------------------------------------------------------------
; =========================================================================
; ИСПРАВЛЕННАЯ ЗАЛИВКА ПАЛИТРЫ (С КОРРЕКТНЫМ АДРЕСОМ ИСТОЧНИКА)
; =========================================================================
; =========================================================================
; ИСПРАВЛЕННАЯ ЗАЛИВКА ПАЛИТРЫ (СТРОГО ПО ИСХОДНИКУ С ПРАВИЛЬНОЙ ДЛИНОЙ)
; =========================================================================
Load_Text_Palette:
    di                      ; Вырубаем прерывания на время подмены памяти

    ; 1. Открываем палитру CRAM на запись в окно процессора #C000
    ld bc, FMADDR           ; Порт #15AF
    ld a, #10               ; Маппим CRAM на адрес #C000, разрешаем запись
    out (c), a
 
    ; 2. Копируем наши 16 цветов (32 байта) прямо в CRAM зетником!
    
    ld hl, Palette_Data     ; Откуда берем (наша dw таблица в хексах #0012)
    ld de, PALET_NUM*32         ; Куда пишем (Окно CRAM + смещение текстовой палитры)
    ld bc, 32               ; Размер палитры (16 цветов * 2 байта)
    ldir                    ; Процессор мгновенно залил цвета без всякого DMA!

    ; 3. Закрываем окно маппинга CRAM, возвращаем обычную память страницы в #C000
    ld bc, FMADDR
    xor a                   ; Пишем 0 для отключения маппинга
    out (c), a
    
    ret

Palette_Data
    ; Порядок db для LDIR: [ Младший байт (gggBBbbb) ], [ Старший байт (0RRrrrGG) ]
    ; Канал 5 бит, уровни 0..24 (24 - максимум). Старшие 2 бита - ЦАП (0, 8, 16, 24),
    ; младшие 3 - ШИМ между ними: без VDAC на Evo даёт полосы - НЕ использовать (Unreal: TS_VDAC=5BIT - линейно).

        ; --- Синяя палитра (как FastTracker 2 на ПК), уровни Кр, Зл, Сн. Только уровни ЦАП
        ; 0, 8, 16, 24: младшие биты - ШИМ, без VDAC на Evo дают полосы. Та же, что тема
        ; Blue в srs/palettes.asm (Pal_Data). Роли - srs/colors.asm
    db #08,#00    ; #0: Фон - тёмно-синий (0, 0, 8)
    db #10,#21    ; #1: Рамки, плашки заголовков (8, 8, 16)
    db #18,#42    ; #2: Светлый голубой - заголовки, каждая 4-я роу (16, 16, 24)
    db #10,#01    ; #3: Фон играющей строки - синий (0, 8, 16)
    db #08,#21    ; #4: Тусклый - соседние паттерны (8, 8, 8)
    db #10,#22    ; #5: Средне-синий, запасной (8, 16, 16)
    db #18,#63    ; #6: Светлый нейтральный - инструмент, период огибающей, шум (24, 24, 24)
    db #18,#22    ; #7: Небесно-голубой - номера роу, кнопки (8, 16, 24)
    db #08,#01    ; #8: Тёмно-синий, запасной (0, 8, 8)
    db #10,#42    ; #9: Серый - текст, параметры (16, 16, 16)
    db #08,#62    ; #A: Янтарный - команды, маркер повтора (24, 16, 8)
    db #18,#63    ; #B: Белый - ноты (24, 24, 24)
    db #00,#40    ; #C: Красный - ошибки (16, 0, 0)
    db #08,#23    ; #D: Зелёный - горящая кнопка (8, 24, 8)
    db #18,#42    ; #E: Фон шапки - светлый серо-голубой (16, 16, 24)
    db #18,#23    ; #F: Курсор - голубой (8, 24, 24)




    dw %0000000000000000    ; 0: Черный
    dw %0000000000001010    ; 1: Синий
    dw %0000000010100000    ; 2: Зеленый
    dw %0000000010101010    ; 3: Циан
    dw %0000101000000000    ; 4: Красный
    dw %0000101000001010    ; 5: Маджента
    dw %0000101001010000    ; 6: Коричневый
    dw %0000101010101010    ; 7: Светло-серый (стандартный текст)
    dw %0000010101010101    ; 8: Темно-серый
    dw %0000010101011111    ; 9: Ярко-синий
    dw %0000010111110101    ; A: Ярко-зеленый
    dw %0000010111111111    ; B: Ярко-циан
    dw %0000111101010101    ; C: Ярко-красный
    dw %0000111101011111    ; D: Ярко-маджента
    dw %0000111111110101    ; E: Желтый
    dw %0000111111111111    ; F: Белый