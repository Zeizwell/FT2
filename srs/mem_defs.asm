; =========================================================================
; КАРТА СТРАНИЦ FT2 (FT2 - самостоятельная SPG, без WC)
; =========================================================================
; Всё системное прижато к началу, за ним данные трека, паттерны - последними,
; чтобы свободное место шло одним куском после них.
; #00      коре
; #01      окно 1 по умолчанию
; #02      стартовый код
; #03      окно 3 по умолчанию
; #04      просмотр паттерна (тулза)
; #05      экран ZX + резидент загрузчика SPG - не трогаем
; #06      банк шрифтов + значки интерфейса
; #07      экран ZX - не трогаем
; #08      графика спрайтов. Формально SGPage занимает 8 страниц #08-#0F, но железо
;          читает только строки используемых тайлов. Курсор - строки 0..15 #08.
;          Спрайты держать в пределах #08 (64 строки тайлов), тогда #09-#0F свободны.
; #09-#0F  тулзы и плагины
; #10-#13  текстовый экран + шрифт (VPage XOR 1), вторая пара - под двойной буфер
; #14-#15  FAT32-драйвер: рабочая память и код
;          (github.com/andrewinsidelazarev/FAT32-Driver-ZX-Evolution)
; #16      трек: заголовок, ордер-лист, каталоги
; #17-#1F  сэмплы, орнаменты, FX, буферы обмена / отмены / экспорта
; #20-#5F  паттерны: 64 страницы = 128 паттернов по 2 на страницу
; #60-#BF  свободно
; #C0-#FF  система: RAM-диск vDOS, буферы и FAT-движок TS-BIOS, вирт. ПЗУ - не трогаем
; =========================================================================

PAGE_CORE0  equ #00
PAGE_CORE1  equ #01
PAGE_CORE2  equ #02
PAGE_CORE3  equ #03

PAGE_TOOL_PATVIEW equ #04   ; тулза просмотра паттерна (окно 1)
PAGE_SPRITE equ #08         ; Спрайты
; Внимательно смотрим сборщик и тд, куда кто грузится через spg!
PAGE_TEXT   EQU #10         ; Текст режим, 128 символов+128 атр на строку
PAGE_FONT   EQU #11         ; Шрифты текст режима
PAGE_FONTS  EQU #06         ; банк шрифтов: слоты по FONT_SIZE
PAGE_FAT_WORK EQU #14       ; FAT32: рабочая память (на время вызова - в окне 0)
PAGE_FAT_CODE EQU #15       ; FAT32: код, таблица входов с #4000 (окно 1)
PAGE_SONG   EQU #16         ; трек: заголовок, ордер-лист, каталоги
PAGE_PATTERNS EQU #20       ; первая страница паттернов
PAGES_PATTERNS EQU 64       ; #20-#5F
    ASSERT PAGES_PATTERNS*(256/PAT_WIDTH) >= PATTERNS_MAX   ; все паттерны влезают
    ASSERT PAGE_PATTERNS+PAGES_PATTERNS <= #C0              ; не лезем в систему

FONT_SIZE       equ #800    ; шрифт 256 символов x 8 байт
FONTS_COUNT     equ 1       ; сколько шрифтов в банке (слоты 0..)
UI_GLYPH_SLOT   equ 7       ; слот банка со значками интерфейса

;------------------------------------------------------------------
; Стек живёт в коре (пейдж 0, окно #0000), чтобы не пропадал при
; переключении тулз в окне 1. Растёт вниз от #3FFF.
; Над коре: #3C00 API, #3D00 системные переменные (см. sdk/plugin.asm).
STACK_TOP   equ #4000
STACK_SIZE  equ #200        ; #3E00..#3FFF

;------------------------------------------------------------------
; Менеджер страниц
; Номера включённых страниц хранятся в SV_PAGES (sdk/plugin.asm), т.к.
; Page0/1 только на запись. Менять страницы ТОЛЬКО макросами, иначе
; SV_PAGES разъедется с железом.
;
; SETPAGE/RESTPAGE и SETPAGE2/3, RESTPAGE2/3 - в sdk/plugin.asm.
; Здесь - то, что нужно только коре:
; MAPPAGE win,page  - включить страницу в окно win (0..3) без сохранения
; SETPAGE0/1 page, RESTPAGE0/1
;
; page - число, регистр (a,b,c,d,e,h,l) или (hl). Портят A, BC.
; Переменную - только через регистр: ld a,(var) / SETPAGE3 a
; (SETPAGE3 (var) соберётся молча, но подставит младший байт адреса!)

    MACRO MAPPAGE win,page
        ld b,page
        ld a,b
        ld (SV_PAGES+win),a     ; сначала тень, потом порт
        ld bc,PAGE0+win*#100
        out (c),a
    ENDM

    MACRO SETPAGE0 page
        SETPAGE 0,page
    ENDM
    MACRO SETPAGE1 page
        SETPAGE 1,page
    ENDM
    MACRO RESTPAGE0
        RESTPAGE 0
    ENDM
    MACRO RESTPAGE1
        RESTPAGE 1
    ENDM
