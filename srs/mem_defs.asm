; =========================================================================
; КАРТА СТРАНИЦ FT2 (FT2 - самостоятельная SPG, без WC)
; =========================================================================
; Спрессовано (2026-10-26): системное и буферы - в начале, без дыр, пул - одним куском до #BF,
; свободное - его хвост. Что грузит SPG (srs/spg.ini) - только в свои страницы; #01, #03, #05 и
; страницы спрайтов кроме #08, #0C-#0D - под то, что заполняется уже после старта.
; #00      коре
; #01      окно (его вид) - PAGE_WINIMG; при старте - окно 1 по умолчанию
; #02      стартовый код
; #03      что под окном - PAGE_WINSAVE; при старте - окно 3 по умолчанию
; #04      просмотр паттерна (тулза)
; #05      отмена и буфер обмена редактора - PAGE_EDBUF (при загрузке SPG здесь экран ZX и
;          резидент загрузчика: пишем только после старта)
; #06      конвертеры (srs/convview.asm, окно 1 на время вызова): импорт PT3 / PT2 / FTC
; #07      плеер, вторая страница (таблицы): окно 2 на время тика
; #08-#0F  блок графики спрайтов (битмап 512x512 = 8 страниц с кратной 8, требование TSU). Спрайты
;          и тайлы берут только #08 (курсор, тайлы) и #0C-#0D (окна осцилляторов, п.25), остальные -
;          наши: #09-#0B шаблоны вида паттерна (тусклый / активный / редактирование; в #09 ещё
;          символы пустой роу), #0E номера роу 00..3F, #0F каталог тулзы диска
; #10-#11  текстовый экран + шрифт. Требование железа - только пара страниц,
;          отличающихся младшим битом (шрифт = VPage XOR 1), кратность не нужна.
; #12-#13  второй экран + шрифт - под двойной буфер
; #14      FAT32-драйвер: код (github.com/andrewinsidelazarev/FAT32-Driver-ZX-Evolution)
; #15      FAT32-драйвер: рабочая память
; #16-#17  страницы треков 1 и 2: заголовок, ордер-лист, каталоги, состояние
;          редактора. Открыто два трека сразу, редактируемый - SV_SONG_PAGE.
; #18      переходник к FAT32-драйверу (srs/disk.asm, окно 2 на время вызова)
; #19      плеер (srs/player.asm): код, окно 1 на время тика в IM1
; #1A      тулза диска (srs/diskview.asm)
; #1B      тулза инструментов и орнаментов
; #1C      тулза Setup / Help
; #1D      компаратор плеера
; #1E-#21  буфер файла, 4 страницы = 64К: модуль (PT3, PT2, FTC) читается целиком,
;          FT2 - потоком через одну страницу; он же - буфер компиляции (PT3)
; #22-#BF  ПУЛ (158): два трека по 68 страниц подряд (64 паттерна, инструменты, орнаменты,
;          строки FX, таблицы и заголовки FX), трек 1 - #22-#65, трек 2 - #66-#A9;
;          #AA-#BF - свободно (22, FREE_PAGES)
; #C0-#FF  система: RAM-диск vDOS, буферы и FAT-движок TS-BIOS, вирт. ПЗУ - не трогаем
; =========================================================================

PAGE_CORE0  equ #00
PAGE_CORE1  equ #01
PAGE_CORE2  equ #02
PAGE_CORE3  equ #03

PAGE_TOOL_PATVIEW equ #04   ; тулза просмотра паттерна (окно 1)
PAGE_CONV         equ #06   ; конвертеры (окно 1, Call_Conv)
PAGE_TOOL_DISK    equ #1A   ; тулза диска: каталог, загрузка и сохранение (окно 1)
PAGE_DIRLIST      equ #0F   ; каталог для тулзы диска (окно 3)
PAGE_TOOL_INSTR   equ #1B   ; тулза инструментов и орнаментов (окно 1)
PAGE_TOOL_OPT     equ #1C   ; тулза настроек Setup (окно 1)
PAGE_CMP          equ #1D   ; компаратор плеера и эталон PT3 (окно 3, srs/cmpview.asm)
PAGE_SPRITE equ #08         ; Спрайты
; Внимательно смотрим сборщик и тд, куда кто грузится через spg!
PAGE_TEXT   EQU #10         ; Текст режим, 128 символов+128 атр на строку
PAGE_FONT   EQU #11         ; Шрифт текст режима = PAGE_TEXT XOR 1 (так берёт ПЛИС); грузит spg (cp866bold.SpecCHR)
    ASSERT PAGE_FONT == (PAGE_TEXT ^ 1)
PAGE_TEXT2  EQU #12         ; второй экран - двойной буфер
PAGE_FONT2  EQU #13
    ASSERT PAGE_FONT2 == (PAGE_TEXT2 ^ 1)
PAGE_FAT_CODE EQU #14       ; FAT32: код, таблица входов с #4000 (окно 1)
PAGE_FAT_WORK EQU #15       ; FAT32: рабочая память (на время вызова - в окне 0)
PAGE_DISK_APP EQU #18       ; переходник к FAT32 (srs/disk.asm): на время вызова - в окне 2
PAGE_PLAYER   EQU #19       ; плеер (srs/player.asm): из IM1 - в окне 1
PAGE_PLAYER2  EQU #07       ;   вторая страница: из IM1 - в окне 2
SONGS_MAX   EQU 2           ; сколько треков открыто сразу
PAGE_SONG1  EQU #16         ; трек 1: заголовок, ордер-лист, каталоги, состояние редактора
PAGE_SONG2  EQU #17         ; трек 2
PAGE_FILEBUF  EQU #1E       ; буфер файла: модуль целиком (до 64К) или поток FT2 (одна страница)
PAGES_FILEBUF EQU 4
PAGE_COMPBUF  EQU PAGE_FILEBUF                  ; буфер откомпилированного трека - он же
PAGES_COMPBUF EQU PAGES_FILEBUF                 ;   (компиляция и загрузка не бывают сразу)
PAGE_POOL     EQU PAGE_FILEBUF+PAGES_FILEBUF    ; пул: паттерны, инструменты обоих треков
PAGE_POOL_END EQU #C0                           ; дальше - система TS-BIOS
PAGE_VIEW_TPL EQU #09                           ; 3 страницы шаблонов: тусклый, активный, редактирование
PAGE_ROWNUM   EQU #0E                           ; номера роу
PAGE_EDBUF    EQU #05                           ; отмена и буфер обмена редактора
PAGE_WINIMG   EQU #01                           ; окно (его вид) - в раскладке экрана
PAGE_WINSAVE  EQU #03                           ; что под окном
PAGE_SPLASH   EQU #28                           ; заставка при старте (выкл): экран #28..#30 - страницы пула
PAGE_SPLASH_PAL EQU PAGE_SPLASH+6               ;   её палитра (до заливки фона)

PAGES_PER_SONG EQU PATTERNS_MAX+4   ; полный трек: паттерн = страница + инструменты + орнаменты + строки FX + таблицы и заголовки FX
PAGE_INS1     EQU PAGE_POOL+PATTERNS_MAX ; инструменты и орнаменты трека 1 (пока место фиксировано)
    ASSERT PAGES_COMPBUF*16384 >= COMPILED_MAX      ; откомпилированный влезает
    ASSERT PAGE_POOL_END-PAGE_POOL >= SONGS_MAX*PAGES_PER_SONG ; два полных трека влезают (158 >= 136)
    ASSERT PAGE_SPRITE%8 == 0                       ; блок графики спрайтов - с кратной 8
    ASSERT PAGE_VIEW_TPL > PAGE_SPRITE && PAGE_VIEW_TPL+3 <= PAGE_SPRITE+4     ; наши - в дырах блока
; Свободно (никому не отдано) - хвост пула за двумя треками, одним куском.
; Распределение жёсткое: у каждого трека свои PAGES_PER_SONG страниц, без динамики
FREE_PAGES      EQU PAGE_POOL_END-PAGE_POOL-SONGS_MAX*PAGES_PER_SONG

;------------------------------------------------------------------
; Стек живёт в коре (пейдж 0, окно #0000), чтобы не пропадал при
; переключении тулз в окне 1. Растёт вниз от #3FFF.
; Над коре: #3C00 API, #3D00 системные переменные (см. sdk/plugin.asm).
;------------------------------------------------------------------
; Кэш CPU. На 14 МГц без кэша каждое обращение к RAM ждёт контроллер DRAM.
; Кэшируем окна 0 (коре, стек, IM1) и 1 (код тулз и плагинов, их таблицы).
; Окна 2,3 - без кэша: туда пишет DMA (экран, паттерны), а запись DMA
; кэш не видит. Если DMA пишет в страницу, подключённую в окно 0/1 -
; кэш надо сбросить (записать 512 байт подряд).
CACHECONF   equ #2BAF
CACHE_WIN   equ %0011       ; биты: окно 0, окно 1

STACK_TOP   equ #4000
STACK_SIZE  equ #200        ; #3E00..#3FFF

;------------------------------------------------------------------
; Менеджер страниц
; Номера включённых страниц хранятся в SV_PAGES (sdk/plugin.asm), т.к.
; Page0/1 только на запись. Менять страницы ТОЛЬКО макросами, иначе
; SV_PAGES разъедется с железом.
;
; SETPAGE/RESTPAGE и SETPAGE2/3, RESTPAGE2/3 - в sdk/plugin.asm.
; Здесь - то, что нужно только коре:
; MAPPAGE win,page  - включить страницу в окно win (0..3) без сохранения
; SETPAGE0/1 page, RESTPAGE0/1
;
; page - число, регистр (a,b,c,d,e,h,l) или (hl). Портят A, BC.
; Переменную - только через регистр: ld a,(var) / SETPAGE3 a
; (SETPAGE3 (var) соберётся молча, но подставит младший байт адреса!)

    MACRO MAPPAGE win,page
        ld b,page
        ld a,b
        ld (SV_PAGES+win),a     ; сначала тень, потом порт
        ld bc,PAGE0+win*#100
        out (c),a
    ENDM

    MACRO SETPAGE0 page
        SETPAGE 0,page
    ENDM
    MACRO SETPAGE1 page
        SETPAGE 1,page
    ENDM
    MACRO RESTPAGE0
        RESTPAGE 0
    ENDM
    MACRO RESTPAGE1
        RESTPAGE 1
    ENDM
