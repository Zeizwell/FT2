; =========================================================================
; СПРАЙТЫ ИНТЕРФЕЙСА (часть коре): палитра и карта. Номера записей SFILE и места графики -
; только отсюда.
;   SFILE (0..84, кто позже - тот поверх): 0..4 - кнопки транспорта (srs/transport.asm),
;     5.. - кнопки интерфейса, 84 - стрелка мыши (srs/mouse.asm).
;   Страница спрайтов PAGE_SPRITE (64 строки по 256 байт = 8 рядов по 64 тайла 8x8): ряды 2..3 -
;     транспорт, 4.. - кнопки интерфейса, ряд 6, колонки 60..63 - стрелка и лапка мыши.
; Палитра спрайтов интерфейса - своя (SPR_PAL), не зависит от темы: цвет 0 у спрайта прозрачный,
; поэтому чёрный - не 0. Уровни ЦАП - только 0, 8, 16, 24 (без VDAC ШИМ даёт полосы), значит
; чистых серых два (8, 16); между ними - серо-голубые.
; =========================================================================
SPR_PAL         equ 14              ; номер палитры (текст - 13)
SPR_PAL_B       equ SPR_PAL<<4      ; в байте "палитра | тайл ст." описателя SFILE

SPC_CLEAR       equ #0              ; прозрачный
SPC_BLACK       equ #1
SPC_DGREY       equ #2              ; тёмно-серый 8,8,8
SPC_DBLUE       equ #3              ; серо-голубой тёмный 8,8,16
SPC_GREY        equ #4              ; серый 16,16,16
SPC_LBLUE       equ #5              ; серо-голубой светлый 16,16,24
SPC_WHITE       equ #6              ; белый 24,24,24
SPC_GREEN       equ #7              ; зелёный (горит, играет)
SPC_LGREEN      equ #8              ; светло-зелёный (его свет)
SPC_DGREEN      equ #9              ; тёмно-зелёный (его тень)
SPC_AMBER       equ #A
SPC_RED         equ #B
SPC_CYAN        equ #C

;-------- Палитра спрайтов интерфейса - в CRAM (DMA). Раз при старте, прерывания ещё выкл
Spr_Pal_Set
        ld hl,Spr_Pal_Dma
        jp set_ports_int

        ALIGN 2                     ; цвет: [gggBBBBB] [0RRRRRGG]
Spr_Pal_Data
        dw 0                        ; #0 прозрачный
        dw 0                        ; #1 чёрный          0,0,0
        dw 8<<10 | 8<<5 | 8         ; #2 тёмно-серый     8,8,8
        dw 8<<10 | 8<<5 | 16        ; #3 серо-голубой    8,8,16
        dw 16<<10 | 16<<5 | 16      ; #4 серый           16,16,16
        dw 16<<10 | 16<<5 | 24      ; #5 серо-голубой    16,16,24
        dw 24<<10 | 24<<5 | 24      ; #6 белый           24,24,24
        dw 8<<10 | 24<<5 | 8        ; #7 зелёный         8,24,8
        dw 16<<10 | 24<<5 | 16      ; #8 светло-зелёный  16,24,16
        dw 0<<10 | 16<<5 | 0        ; #9 тёмно-зелёный   0,16,0
        dw 24<<10 | 16<<5 | 8       ; #A янтарь          24,16,8
        dw 24<<10 | 0<<5 | 0        ; #B красный         24,0,0
        dw 8<<10 | 24<<5 | 24       ; #C голубой         8,24,24
        dw 0, 0, 0                  ; #D..#F свободны
Spr_Pal_End
    ASSERT Spr_Pal_End-Spr_Pal_Data == 32
SPR_CRAM        equ SPR_PAL*16      ; первый цвет палитры в CRAM (слова)
Spr_Pal_Dma
        db high DMASADDRL, low Spr_Pal_Data, high DMASADDRH, high Spr_Pal_Data, high DMASADDRX, PAGE_CORE0
        db high DMADADDRL, (SPR_CRAM&127)*2, high DMADADDRH, SPR_CRAM>>7, high DMADADDRX, 0
        db high DMALEN, 16-1, high DMANUM, 0, high DMACTR, DMA_RAM_CRAM, #FF
